-- Mod 2^32 after every step, so each value stays below 2^53 and is exact.
local function hash(text, multiplier, seed)
	local h = seed
	for i = 1, #text do
		h = (h * multiplier + text:byte(i)) % 4294967296
	end
	return h
end

local function name_of(player_id)
	local id = tostring(player_id):lower()
	local deck = DECKS[hash(id, 33, 5381) % #DECKS + 1]
	local joker = JOKERS[hash(id, 31, 52711) % #JOKERS + 1]
	return deck .. ' ' .. joker
end

MPAPI.ban_name = {
	decks = DECKS,
	jokers = JOKERS,
	name_of = name_of,
}

return MPAPI.ban_name
